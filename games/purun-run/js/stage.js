// =====================================================
//  ステージ（文字列マップ）
//  1文字 = 1マス（32×32ピクセル）。全部の行を同じ長さにすること。
//
//  .  なにもない
//  #  地面
//  B  レンガブロック
//  ?  アイテムブロック（下から叩くとアイテムが出る：次の段階で追加）
//  H  かたいブロック（階段や足場）
//  P  柱（土管のような障害物。2マス幅で縦に並べる）
//  S  スタート位置
//  e  敵「どんぐりん」（ゆっくり歩く。足場の端から落ちる）
//  k  敵「ツノカブ」（速く歩く。足場の端で引き返す）
//
//  ※ 地面の '#' がない列は「穴」になります。
//  ※ 敵は、置いたマスの床の上から歩き始めます（最初は左向き）。
// =====================================================
