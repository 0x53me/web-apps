// 壁や床として通り抜けられない文字
const SOLID_TILES = '#B?*UHP';
// 敵を表す文字（enemy.js の ENEMY_TYPES と対応）
const ENEMY_CHARS = 'ek';

// マップを扱いやすい形にしたもの
class Stage {
  constructor(def) {
    this.name = def.name;
    this.rows = def.map.map(line => line.split(''));   // [行][列] で1文字ずつ取り出せる
    this.rowCount = this.rows.length;
    this.colCount = this.rows[0].length;
    this.width = this.colCount * CONFIG.TILE;          // ステージ全体の幅（ピクセル）
    this.height = this.rowCount * CONFIG.TILE;

    // 行の長さがそろっているか確認（ずれていると当たり判定がおかしくなる）
    this.rows.forEach((r, i) => {
      if (r.length !== this.colCount) console.warn(`ステージの ${i} 行目の長さが違います（${r.length} 文字）`);
    });

    // スタート位置 'S' と敵の位置を取り出し、マップからは消しておく
    this.start = { x: 2 * CONFIG.TILE, y: 0 };
    this.enemySpawns = [];   // { type, col, row }
    this.coinSpawns = [];    // { col, row }
    this.rows.forEach((r, row) => r.forEach((ch, col) => {
      if (ch === 'C') {
        this.coinSpawns.push({ col, row });
        r[col] = '.';
      } else if (ch === 'F') {
        this.goalCell = { col, row };
        r[col] = '.';
      } else if (ch === 'S') {
        this.start = { x: col * CONFIG.TILE + (CONFIG.TILE - CONFIG.PLAYER_W) / 2, y: (row + 1) * CONFIG.TILE - CONFIG.PLAYER_H };
        r[col] = '.';
      } else if (ENEMY_CHARS.includes(ch)) {
        this.enemySpawns.push({ type: ch, col, row });
        r[col] = '.';
      }
    }));
    this.computeGoal();
  }

  // ゴールの旗ざおの位置と大きさを計算しておく（真下の床まで）
  // goal = { x, top, bottom, w } … x は旗ざおの左端
  computeGoal() {
    if (!this.goalCell) { this.goal = null; return; }
    const T = CONFIG.TILE, { col, row } = this.goalCell;
    let floorRow = row + 1;
    while (floorRow < this.rowCount && !this.isSolid(col, floorRow)) floorRow++;
    this.goal = { x: col * T + T / 2 - 3, w: 6, top: row * T + 6, bottom: floorRow * T, col };
  }

  // (列, 行) の文字を返す。ステージの外は、左右は壁、上下は空として扱う
  tileAt(col, row) {
    if (col < 0 || col >= this.colCount) return '#';
    if (row < 0 || row >= this.rowCount) return '.';
    return this.rows[row][col];
  }

  // マスの文字を書き換える（? を叩いて U にする、など）
  setTile(col, row, ch) {
    if (row >= 0 && row < this.rowCount && col >= 0 && col < this.colCount) this.rows[row][col] = ch;
  }

  isSolid(col, row) {
    return SOLID_TILES.includes(this.tileAt(col, row));
  }

  // 四角形（x, y, w, h）がどこかの壁・床と重なっているか
  boxHitsSolid(x, y, w, h) {
    const T = CONFIG.TILE;
    const c0 = Math.floor(x / T), c1 = Math.floor((x + w - 0.001) / T);
    const r0 = Math.floor(y / T), r1 = Math.floor((y + h - 0.001) / T);
    for (let r = r0; r <= r1; r++) {
      for (let c = c0; c <= c1; c++) {
        if (this.isSolid(c, r)) return { col: c, row: r };
      }
    }
    return null;
  }
}
